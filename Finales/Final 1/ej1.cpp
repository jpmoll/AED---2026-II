struct coord {
    int x;
    int y;
    coord(int xx, int yy) {
        x = xx;
        y = yy;
    }
};

void caminos(coord a,vector<coord> &caminos) {
    int x = a.x, y = a.y;
    if (x != 18) {
        if (m[x + 1][y] == '#') {
            caminos.push_back(coord(x + 1, y));
        }
    }
    if (x != 0) {
        if (m[x - 1][y] == '#') {
            caminos.push_back(coord(x + 1, y));
        }
    }
    if (y != 18) {
        if (m[x][y + 1] == '#') {
            caminos.push_back(coord(x + 1, y));
        }
    }
    if (y != 0) {
        if (m[x][y - 1] == '#') {
            caminos.push_back(coord(x + 1, y));
        }
    }
    
}

